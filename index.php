                        card.style.setProperty('--my', percentY.toFixed(1) + '%');
                        card.style.setProperty('--foil-pos-x', (100 - percentX).toFixed(1) + '%');
                        card.style.setProperty('--foil-pos-y', (100 - percentY).toFixed(1) + '%');
                    }

