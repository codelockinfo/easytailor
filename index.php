            function getDirection(e, elem) {
                var rect = elem.getBoundingClientRect();
                var w = rect.width;
                var h = rect.height;
                var x = (e.clientX - rect.left - (w / 2)) * (w > h ? (h / w) : 1);
                var y = (e.clientY - rect.top - (h / 2)) * (h > w ? (w / h) : 1);
